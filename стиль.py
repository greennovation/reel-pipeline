def _слить(основа: dict[str, Any], дополнение: dict[str, Any]) -> dict[str, Any]:
    """Возвращает рекурсивное слияние двух словарей, не меняя аргументы."""
    результат = deepcopy(основа)
    for ключ, значение in дополнение.items():
        если_словари = isinstance(результат.get(ключ), dict) and isinstance(значение, dict)
        результат[ключ] = _слить(результат[ключ], значение) if если_словари else deepcopy(значение)
    return результат


def _первый_yaml_блок(текст: str) -> str | None:
    """Извлекает содержимое первого блока ```yaml, не разбирая Markdown."""
    совпадение = re.search(
        r"^[ \t]*```yaml[ \t]*\r?\n(.*?)(?:\r?\n)?^[ \t]*```[ \t]*$",
        текст,
        flags=re.IGNORECASE | re.MULTILINE | re.DOTALL,
    )
    return совпадение.group(1) if совпадение else None


def загрузить_стиль(путь: str | Path) -> dict[str, Any]:
    """Загружает первый YAML-блок из Markdown и дополняет его умолчаниями.

    Отсутствующий файл и Markdown без блока являются нормальным состоянием:
    оба случая возвращают независимую копию :data:`УМОЛЧАНИЯ`.
    """
    файл = Path(путь)
    if not файл.is_file():
        return deepcopy(УМОЛЧАНИЯ)

    текст = файл.read_text(encoding="utf-8")
    блок = _первый_yaml_блок(текст)
    if блок is None:
        return deepcopy(УМОЛЧАНИЯ)

    try:
        данные = yaml.safe_load(блок)
    except yaml.YAMLError as ошибка:
        метка = getattr(ошибка, "problem_mark", None)
        # ``problem_mark.line`` считает от начала YAML, а человеку нужна
        # строка именно Markdown-файла, который он открыл в редакторе.
        смещение = текст[: текст.find(блок)].count("\n")
        строка = смещение + метка.line + 1 if метка is not None else "неизвестна"
        причина = getattr(ошибка, "problem", str(ошибка))
        raise ValueError(
            f"Не удалось прочитать YAML в файле «{файл}», строка {строка}: {причина}"
        ) from ошибка

    if данные is None:
        данные = {}
    if not isinstance(данные, dict):
        raise ValueError(f"YAML в файле «{файл}» должен содержать словарь настроек")
    return _слить(УМОЛЧАНИЯ, данные)


def цвет(строка: str) -> tuple[int, int, int]:
    """Преобразует шестнадцатеричный цвет ``RRGGBB`` в кортеж RGB."""
    if not isinstance(строка, str):
        raise ValueError(f"Некорректный цвет {строка!r}: ожидается строка RRGGBB")
    значение = строка.strip()
    if значение.startswith("#"):
        значение = значение[1:]
    if not re.fullmatch(r"[0-9a-fA-F]{6}", значение):
        raise ValueError(
            f"Некорректный цвет «{строка}»: ожидается шесть шестнадцатеричных символов RRGGBB"
        )
    return tuple(int(значение[номер : номер + 2], 16) for номер in range(0, 6, 2))
