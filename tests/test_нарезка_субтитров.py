"""Проверки смысловой нарезки субтитров."""
from copy import deepcopy

import cut_reel
import субтитры_нарезка
from стиль import УМОЛЧАНИЯ, параметры_субтитров


def _параметры() -> dict:
    return параметры_субтитров(deepcopy(УМОЛЧАНИЯ))


def _слова(текст: str, шаг: float = 0.4) -> list[dict]:
    слова = []
    время = 0.0
    for слово in текст.split():
        слова.append({"text": слово, "start": время, "end": время + шаг})
        время += шаг
    return слова


def test_служебное_слово_не_висит_в_конце_строки():
    параметры = _параметры()
    параметры["символов_в_строке"] = 14
    строки = субтитры_нарезка.перенести(_слова("поставил камеру на стол"), параметры)

    хвосты = [строка[-1]["text"].lower() for строка in строки[:-1]]
    assert not (set(хвосты) & субтитры_нарезка.СЛУЖЕБНЫЕ), хвосты
    assert len(строки) > 1


def test_ширина_меряется_шрифтом_а_не_числом_символов():
    параметры = _параметры()
    шрифт = cut_reel.make_font(параметры, 600)
    узкие = _слова("iii iii iii iii iii iii")
    широкие = _слова("шшш шшш шшш шшш шшш шшш")

    строк_узких = len(субтитры_нарезка.перенести(узкие, параметры, шрифт))
    строк_широких = len(субтитры_нарезка.перенести(широкие, параметры, шрифт))

    # По числу символов оба текста одинаковы. По реальной ширине широкий длиннее.
    assert строк_широких > строк_узких


def test_строка_не_вылезает_за_безопасную_зону():
    параметры = _параметры()
    шрифт = cut_reel.make_font(параметры, 600)
    предел = субтитры_нарезка.предельная_ширина(параметры)

    for строка in субтитры_нарезка.перенести(_слова("ролик собирается из съёмки на кухне за сорок минут"), параметры, шрифт):
        текст = " ".join(слово["text"] for слово in строка)
        assert шрифт.getlength(текст) <= предел, текст


def test_план_помощника_задаёт_границы_реплик():
    параметры = _параметры()
    слова = _слова("цифровой пульт жизни это каркас а не приложение")

    реплики = субтитры_нарезка.сгруппировать(слова, параметры, план=[3, 4])

    assert [len(р) for р in реплики] == [3, 1, 4]
    assert [с["text"] for с in реплики[0]] == ["цифровой", "пульт", "жизни"]


def test_без_плана_длинная_пауза_начинает_новую_реплику():
    параметры = _параметры()
    слова = _слова("первая мысль")
    пауза = float(параметры["пауза_новой_фразы"]) + 0.5
    слова.append({"text": "вторая", "start": слова[-1]["end"] + пауза, "end": слова[-1]["end"] + пауза + 0.4})

    реплики = субтитры_нарезка.сгруппировать(слова, параметры)

    assert len(реплики) == 2
    assert [с["text"] for с in реплики[1]] == ["вторая"]


def test_группировка_через_cut_reel_принимает_план():
    параметры = _параметры()
    слова = _слова("раз два три четыре")

    реплики = cut_reel.group_phrases(слова, параметры, план=[2])

    assert [[с["text"] for с in р] for р in реплики] == [["раз", "два"], ["три", "четыре"]]
