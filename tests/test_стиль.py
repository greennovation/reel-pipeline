from pathlib import Path
import re

import pytest
import yaml

from стиль import УМОЛЧАНИЯ, загрузить_стиль, цвет


def _пути_ключей(словарь: dict, путь: tuple[str, ...] = ()) -> set[tuple[str, ...]]:
    """Возвращает все пути ключей, включая промежуточные словари."""
    результат = set()
    for ключ, значение in словарь.items():
        путь_ключа = путь + (ключ,)
        результат.add(путь_ключа)
        if isinstance(значение, dict):
            результат.update(_пути_ключей(значение, путь_ключа))
    return результат


def test_фикстура_фирменного_стиля_читается():
    файл = Path(__file__).parent / "данные" / "Фирменный стиль.md"

    стиль = загрузить_стиль(файл)

    assert стиль["формат"]["ширина"] == 1080
    assert стиль["субтитры"]["цвет_активного_слова"] == "#FFD23F"


def test_ключи_умолчаний_совпадают_с_продуктовым_шаблоном():
    файл = Path(__file__).parent / "данные" / "Фирменный стиль.md"
    текст = файл.read_text(encoding="utf-8")
    совпадение = re.search(r"```yaml\n(.*?)\n```", текст, flags=re.DOTALL)
    assert совпадение is not None
    ключи_шаблона = _пути_ключей(yaml.safe_load(совпадение.group(1)))

    assert _пути_ключей(загрузить_стиль(файл)) == ключи_шаблона


def test_стиль_сливается_с_умолчаниями_рекурсивно(tmp_path: Path):
    файл = tmp_path / "стиль.md"
    файл.write_text("```yaml\nформат:\n  ширина: 720\nсубтитры:\n  размер: 60\n```", encoding="utf-8")

    стиль = загрузить_стиль(файл)

    assert стиль["формат"] == {"ширина": 720, "высота": 1920, "кадров_в_секунду": 30}
    assert стиль["субтитры"]["размер"] == 60
    assert стиль["субтитры"]["шрифт"] == "Unbounded.ttf"


def test_нет_файла_возвращает_независимые_умолчания(tmp_path: Path):
    первый = загрузить_стиль(tmp_path / "нет.md")
    первый["формат"]["ширина"] = 1

    assert загрузить_стиль(tmp_path / "нет.md") == УМОЛЧАНИЯ


def test_без_yaml_блока_возвращает_умолчания(tmp_path: Path):
    файл = tmp_path / "стиль.md"
    файл.write_text("# Только памятка\n", encoding="utf-8")

    assert загрузить_стиль(файл) == УМОЛЧАНИЯ


def test_берётся_только_первый_yaml_блок(tmp_path: Path):
    файл = tmp_path / "стиль.md"
    файл.write_text(
        "```yaml\nформат: {ширина: 720}\n```\n```yaml\nформат: {высота: 100}\n```",
        encoding="utf-8",
    )

    assert загрузить_стиль(файл)["формат"] == {
        "ширина": 720,
        "высота": 1920,
        "кадров_в_секунду": 30,
    }


def test_битый_yaml_называет_файл_и_строку(tmp_path: Path):
    файл = tmp_path / "сломанный.md"
    файл.write_text("```yaml\nформат: [\n```", encoding="utf-8")

    with pytest.raises(ValueError, match=r"сломанный\.md.*строка 2"):
        загрузить_стиль(файл)


@pytest.mark.parametrize(
    ("вход", "ожидание"),
    [("#FFD23F", (255, 210, 63)), ("ffd23f", (255, 210, 63)), ("FfD23f", (255, 210, 63))],
)
def test_цвет(вход: str, ожидание: tuple[int, int, int]):
    assert цвет(вход) == ожидание


def test_некорректный_цвет_даёт_понятную_ошибку():
    with pytest.raises(ValueError, match="Некорректный цвет"):
        цвет("жёлтый")
