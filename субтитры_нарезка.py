#!/usr/bin/env python3
"""Нарезка речи на субтитры: смысловая группировка и перенос по реальному шрифту.

Два правила, из-за которых субтитры выглядят машинными.

Первое: перенос по числу символов. В кириллице «шшшш» и «iiii» это четыре символа
и разная ширина, поэтому подпись то вылезает за безопасную зону, то занимает
половину доступного места. Здесь ширина меряется тем же шрифтом, которым потом
рисуется кадр.

Второе: разрыв словосочетания. Предлог, союз и частица отрываются от своего слова
и повисают в конце строки. Здесь служебное слово всегда уходит вниз вместе со следующим.

Смысловую нарезку на реплики делает помощник, а не этот модуль: он умеет только
механику. Готовый список границ можно передать в ``сгруппировать`` параметром ``план``.
"""
from __future__ import annotations

from typing import Any, Iterable, Optional, Sequence

# Служебные слова, которые нельзя оставлять последними в строке: читаются как обрыв.
СЛУЖЕБНЫЕ = {
    "в", "во", "на", "над", "под", "по", "за", "из", "изо", "от", "ото", "до", "к", "ко",
    "с", "со", "у", "о", "об", "обо", "при", "про", "для", "без", "через", "между",
    "и", "а", "но", "да", "или", "либо", "то", "что", "чтобы", "как", "если", "когда",
    "не", "ни", "же", "ли", "бы", "вот", "уже", "ещё", "еще", "это", "этот", "эта",
    "мой", "моя", "моё", "мое", "наш", "наша", "свой", "своя", "его", "её", "ее", "их",
}

# Доля кадра по краям, куда значимое не заходит. Совпадает с безопасной зоной канона
# монтажа: для ширины 1080 это отступ 96 точек с каждой стороны.
ДОЛЯ_ПОЛЯ = 0.089


def _слово(w: Any) -> str:
    return str(w["text"]).strip()


def предельная_ширина(параметры: dict[str, Any]) -> float:
    """Возвращает предельную ширину строки субтитра в точках кадра."""
    ширина = float(параметры["ширина"])
    return ширина * (1.0 - 2.0 * ДОЛЯ_ПОЛЯ)


def _ширина_текста(текст: str, шрифт: Any) -> float:
    try:
        return float(шрифт.getlength(текст))
    except AttributeError:  # очень старый Pillow
        return float(шрифт.getsize(текст)[0])


def перенести(
    слова: Sequence[Any],
    параметры: dict[str, Any],
    шрифт: Any = None,
) -> list[list[Any]]:
    """Переносит слова по строкам, меряя ширину настоящим шрифтом.

    Шрифт не передали, значит остаётся старая оценка по числу символов: модуль
    обязан работать и там, где рендерер шрифт ещё не построил.
    """
    if not слова:
        return []

    предел_точек = предельная_ширина(параметры) if шрифт is not None else None
    предел_символов = int(параметры["символов_в_строке"])

    def влезает(кандидат: list[Any]) -> bool:
        текст = " ".join(_слово(x) for x in кандидат)
        if предел_точек is not None:
            return _ширина_текста(текст, шрифт) <= предел_точек
        return len(текст) <= предел_символов

    строки: list[list[Any]] = []
    строка: list[Any] = []
    for w in слова:
        кандидат = строка + [w]
        if строка and not влезает(кандидат):
            строки.append(строка)
            строка = [w]
        else:
            строка = кандидат
    if строка:
        строки.append(строка)

    return _снять_висячие(строки, параметры, шрифт)


def _снять_висячие(
    строки: list[list[Any]],
    параметры: dict[str, Any],
    шрифт: Any,
) -> list[list[Any]]:
    """Переносит служебное слово с конца строки вниз, к его слову.

    Перенос делается только если строка снизу после этого всё ещё влезает: иначе
    лечение висячего предлога выталкивает подпись за безопасную зону, а это хуже.
    """
    предел_точек = предельная_ширина(параметры) if шрифт is not None else None
    предел_символов = int(параметры["символов_в_строке"])

    def влезает(строка: list[Any]) -> bool:
        текст = " ".join(_слово(x) for x in строка)
        if предел_точек is not None:
            return _ширина_текста(текст, шрифт) <= предел_точек
        return len(текст) <= предел_символов

    for i in range(len(строки) - 1):
        текущая = строки[i]
        if len(текущая) < 2:
            continue
        последнее = _слово(текущая[-1]).lower().strip(".,!?;:»«…")
        if последнее not in СЛУЖЕБНЫЕ:
            continue
        if влезает([текущая[-1]] + строки[i + 1]):
            строки[i + 1].insert(0, текущая.pop())
    return [с for с in строки if с]


def сгруппировать(
    слова: Sequence[Any],
    параметры: dict[str, Any],
    шрифт: Any = None,
    план: Optional[Iterable[int]] = None,
) -> list[list[Any]]:
    """Бьёт поток слов на реплики.

    ``план`` это список номеров слов, с которых начинается новая реплика: его
    готовит помощник по смыслу. Плана нет, значит режем механически по паузе
    и по вместимости двух строк.
    """
    слова = list(слова)
    if not слова:
        return []

    if план is not None:
        границы = sorted({int(n) for n in план if 0 < int(n) < len(слова)})
        реплики: list[list[Any]] = []
        предыдущая = 0
        for граница in границы:
            реплики.append(слова[предыдущая:граница])
            предыдущая = граница
        реплики.append(слова[предыдущая:])
        return [р for р in реплики if р]

    пауза = float(параметры["пауза_новой_фразы"])
    строк = int(параметры["строк_максимум"])
    реплики = []
    текущая: list[Any] = []
    for w in слова:
        новая_после_паузы = bool(текущая) and w["start"] - текущая[-1]["end"] > пауза
        переполнена = bool(текущая) and len(перенести(текущая + [w], параметры, шрифт)) > строк
        if новая_после_паузы or переполнена:
            реплики.append(текущая)
            текущая = [w]
        else:
            текущая.append(w)
    if текущая:
        реплики.append(текущая)
    return реплики
